# --- substitution helpers: every rule must match at least once unless marked optional ------------------

def set_first(pattern, replacement):
    return ("first", pattern, replacement, False)


def set_all(pattern, replacement, optional=False):
    return ("all", pattern, replacement, optional)


def scale_all(pattern, factor, optional=False):
    """Multiplies the first group (a plain number) of every match."""
    def repl(m):
        value = float(m.group(1)) * factor
        return m.group(0).replace(m.group(1), f"{value:.4g}", 1)
    return ("all", pattern, repl, optional)


def label(name, value):
    return set_all(r"label %s\([^)]*\)" % name, f"label {name}({value})")


def name(display):
    return set_first(r'name: "[^"]*"', f'name: "{display}"')


def audio(factor, ir=None):
    rules = [set_all(r"audio_volume: ([^,\n]+?),", lambda m: f"audio_volume: ({m.group(1).strip()}) * {factor},")]
    if ir:
        rules.append(set_all(r"impulse_response: ir_lib\.\w+", f"impulse_response: ir_lib.{ir}"))
    return rules


CAM_DURATION = r"duration_at_50_thou: ([\d.]+) \* units\.deg"
CAM_LIFT = r"lift: ([\d.]+) \* units\.(?:mm|thou)"
INTAKE_FLOW = r"intake_flow_rate: k_carb\(([\d.]+)\)"
CHAMBER = r"chamber_volume: [\d.]+(?: \* [\d.]+)* \* units\.cc"


def bbc_camshaft(intake_deg, exhaust_deg, lift_thou, separation_deg):
    """Replaces the 454's stock camshaft with harmonic lobes on the part library's big-block builder."""
    block = (
        f"harmonic_cam_lobe wspc2_intake_lobe(duration_at_50_thou: {intake_deg} * units.deg, gamma: 1.1, "
        f"lift: {lift_thou} * units.thou, steps: 256)\n"
        f"    harmonic_cam_lobe wspc2_exhaust_lobe(duration_at_50_thou: {exhaust_deg} * units.deg, gamma: 1.1, "
        f"lift: {lift_thou} * units.thou, steps: 256)\n"
        f"    chevy_bbc_camshaft_builder camshaft(\n"
        f"        lobe_profile: wspc2_intake_lobe,\n"
        f"        intake_lobe_profile: wspc2_intake_lobe,\n"
        f"        exhaust_lobe_profile: wspc2_exhaust_lobe,\n"
        f"        lobe_separation: {separation_deg} * units.deg)"
    )
    return set_first(r"chevy_454_stock_camshaft camshaft\(\)", block)


