# audio_profile tags that stay on the synthetic families of UWSPC2VehicleAudioComponent
SYNTHETIC_TAGS = {"Tank_Turbine": "SyntheticTurbine", "GolfCart_Electric": "SyntheticElectric"}


def apply_rule(text, rule, arch_id):
    mode, pattern, replacement, optional = rule
    count = 1 if mode == "first" else 0
    new_text, n = re.subn(pattern, replacement, text, count=count)
    if n == 0 and not optional:
        sys.exit(f"[{arch_id}] rule did not match: {pattern}")
    return new_text


def rpm_grid(vehicles):
    low = min(v["idle_rpm"] for v in vehicles) * LOW_MARGIN
    high = max(v["max_rpm"] for v in vehicles) * HIGH_MARGIN
    ratio = (high / low) ** (1.0 / (RPM_POINTS - 1))
    return [int(round(low * ratio ** i / 10.0) * 10) for i in range(RPM_POINTS)]


def main():
    fleet = json.load(open(FLEET, encoding="utf-8"))
    fleet = fleet["vehicles"] if isinstance(fleet, dict) and "vehicles" in fleet else fleet
    by_tag = {}
    for entry in fleet:
        specs = entry["real_specs"]
        by_tag.setdefault(specs["audio_profile"], []).append(specs)

    covered = {tag for arch in ARCHETYPES for tag in arch["tags"]} | set(SYNTHETIC_TAGS)
    missing = sorted(set(by_tag) - covered)
    if missing:
        sys.exit(f"audio_profile tags without an archetype: {missing}")

    os.makedirs(OUT_DIR, exist_ok=True)
    manifest = {"schemaVersion": 1, "sampleRate": 48000, "loads": [0.0, 0.45, 1.0],
                "stabilizeSeconds": 0.75, "captureSeconds": 2.2,
                "startup": {"crankSeconds": 0.55, "catchSeconds": 1.45, "settleSeconds": 4.5},
                "syntheticTags": SYNTHETIC_TAGS, "archetypes": []}

    for arch in ARCHETYPES:
        vehicles = [v for tag in arch["tags"] for v in by_tag.get(tag, [])]
        if not vehicles:
            sys.exit(f"[{arch['id']}] no vehicle uses its tags {arch['tags']}")
        grid = rpm_grid(vehicles)
        redline = int(math.ceil((grid[-1] + 150) / 50.0) * 50)
        rev_limit = redline + 300
        node = "wspc2_" + arch["id"][len("arch_"):]

        with open(os.path.join(BASES, arch["base"]), encoding="utf-8") as f:
            text = f.read()
        rules = [name(arch["display"]),
                 set_all(r"redline: [\d.]+ \* units\.rpm", f"redline: {redline} * units.rpm"),
                 set_all(r"rev_limit: [\d.]+ \* units\.rpm", f"rev_limit: {rev_limit} * units.rpm")]
        rules += arch["rules"]
        for rule in rules:
            text = apply_rule(text, rule, arch["id"])
        text, renamed = re.subn(r"\b%s\b" % re.escape(arch["node"]), node, text)
        if renamed == 0:
            sys.exit(f"[{arch['id']}] engine node {arch['node']} not found")

        header = HEADER.format(id=arch["id"], display=arch["display"], base=arch["base"],
                               tags=", ".join(arch["tags"]), grid=", ".join(map(str, grid)))
        preset_path = os.path.join(OUT_DIR, arch["id"] + ".mr")
        with open(preset_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(header + text)

        manifest["archetypes"].append({
            "id": arch["id"], "displayName": arch["display"],
            "preset": f"Tools/audio/pipeline/presets/{arch['id']}.mr", "entry": node,
            "basePreset": arch["base"], "audioProfiles": arch["tags"],
            "vehicles": len(vehicles), "idleRpm": grid[0], "rpms": grid,
            "redlineRpm": redline, "revLimitRpm": rev_limit,
        })
        print(f"{arch['id']:24s} {len(vehicles):2d} cars  rpm {grid[0]}..{grid[-1]}  redline {redline}")

    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    print(f"wrote {len(ARCHETYPES)} presets to {OUT_DIR} and {MANIFEST}")


if __name__ == "__main__":
    main()
